// ==========================================================
// 世界7不思議: 7問の問題データ
//
// 既存の謎解きトロフィー126問(js/puzzle-questions.js、PUZZLE_QUESTIONS)とは
// 完全に別の配列として管理する。理由:
//   - 「通常の謎解きトロフィーを全問獲得すると世界7不思議が解放される」
//     という条件の分母(PUZZLE_QUESTIONS)に、この7問自身が混入して
//     循環参照・無限ループを起こさないようにするため(構造上、この配列を
//     PUZZLE_QUESTIONSに入れない限り絶対に混入しない)。
//   - 一覧画面での専用デザイン(封印カード・ロック演出)の出し分けを
//     def.category(js/trophy.js側で付与)で安全に判定できるようにするため。
//
// 回答の判定方式そのものは既存の謎解きと完全に同じ(js/puzzle-judge.jsの
// judge(questionId, selectedIds)、js/puzzle.jsの国旗選択画面)を再利用する。
// 複雑な暗号の解読はプレイヤーが画面の外で行うものであり、回答操作自体は
// 「正解の国旗を選ぶ」だけで完結する(暗号の自動復号をゲーム側が代わりに
// 行うことはしない)。
//
// judgeModeは7問すべて"unordered"(1か国を選ぶだけなので、順不同の判定を
// そのまま使っても単一国同士の比較になり、意味的に単一正解判定と同じ)。
//
// answerIdsはjs/countries.js(COUNTRIES)の既存id(ペルー=pe、エストニア=ee、
// ニジェール=ne、マリ=ml、カメルーン=cm、サントメ・プリンシペ=st、
// ミクロネシア連邦=fm)。7か国とも既存のCOUNTRIES(198件)の中に実在し、
// MAP_ONLY_REGIONSの追加は不要(検証スクリプトで確認済み)。
//
// questionText/explanationTextは、企画書「世界7不思議_最終実装企画書
// (2026年11月25日・最終統合版)」の「正式採用7問」章にある「プレイヤー向け
// 問題文」「正解後に表示する解説文」を、一字一句そのまま採用している
// (創作での代用は行っていない)。解法・鍵・暗号名称・対応表といった
// 「実装・検証用メモ(非公開)」の内容は、問題文には一切転載せず、正解後の
// 解説文にのみ記載している(企画書自身の区分どおり)。
//
// 企画書の資料区分:
//   - Ⅳの詩、Ⅴ「終章 ― 星の継承」、Ⅵの二部構成、Ⅶの二部構成は
//     「正式採用の出題全文」(そのまま採用)。
//   - Ⅰの6×6暗号表・Ⅳの4つの手掛かり・Ⅴ前半の三旋律描写は「実装用復元案
//     (改訂時に新規設計)」である旨が企画書に明記されており、その注記を
//     保ったまま採用している。
//   - Ⅲの問題文は原文および地図投影法の検証が必要と企画書自身が明記して
//     いるため、採用した地理・文化要素に基づく復元案として扱う(地図の
//     対角線交点が実際にニジェール領内に収まることは検算済み)。
//   - 暗号表・暗号文・座標・引用文から正解国へ到達する手順は、実装時に
//     専用の検算スクリプトで独立に再現・確認している(ADFGVX/エニグマ/
//     モールス+ヴィジュネル/英語名並び替え+座標+4語目抽出は厳密に再現、

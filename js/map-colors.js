// ==========================================================
// 世界地図モード専用: 国・地域ごとの固定パステルカラー(事前生成データ)
//
// 学習用地球儀のように、国ごとに異なるやさしいパステルカラーで塗り分ける
// ための配色データ。実行時には一切計算せず、ここに保存した固定の
// mapCode→色の対応表を読むだけにする(回転・ズームのたびに再計算しない)。
//
// 生成方法(assets/map/world-countries.geojson の216フィーチャが対象):
//   1. 各国・地域ポリゴンの境界線どうしの距離がほぼ0(実質的に接している)
//      組み合わせを「陸上で国境を接する」とみなし、隣接グラフを作る
//      (Natural Earthデータは共有国境で全く同じ座標列を使っているため、
//      この判定は非常に高精度。唯一、マカオ-中国だけはデータの簡略化で
//      約2.3kmの隙間ができていたため、実際の陸上国境として手動で追加した)
//   2. 隣接国どうしは必ず別の色になるよう、グラフ彩色アルゴリズム
//      DSATUR(彩度=割当済み隣接色の種類数が最大のノードを優先的に
//      確定させる手法。networkxのgreedy_color/saturation_largest_first)
//      で6色以内に彩色した
//   3. 国境を共有しなくても、500km以内にある地域どうしは「近い」とみなし、
//      同じく異なる色になるよう制約に加えた(狭い海峡・至近距離の島国が
//      同じ色になりすぎないようにするため。500kmより広げると6色では
//      彩色できなくなることを検証済みで、6色に収まる上限がこの値)
//   4. ハワイ(HI)はアメリカ合衆国(USA)の一部として扱われるため
//      (js/map-regions.js の parentQuizId)、必ず同じ色になるよう
//      彩色前に1つのノードとして統合した
//   5. 国境・近距離のどちらの制約も持たない孤立した島国・地域は、
//      同じ大洋・地域にまとまる島国どうし(2500km程度)でできるだけ
//      色が重ならないよう、周辺で使われていない色を優先して配分した
//
// 検証結果: 配色対象216件 / 使用色数6 / 陸上隣接ペアでの同色衝突0件(500km以内の近接ペアでも0件)
//
// キーはGeoJSONの各フィーチャのid(= countries.js/map-regions.jsのmapCode)。
// map.js側はこのオブジェクトをfeat.idで直接引くだけで、countryByMapCode等の
// 既存の仕組みには一切手を加えていない。
// ==========================================================

